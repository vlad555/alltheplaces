export interface YouTubeVideo {
  id: string
  title: string
  description: string
  publishedAt: string
  publishDate: Date // Parsed publishedAt as Date
  uploadDate: Date // Same as publishDate for compatibility
  thumbnailUrl: string
  duration: string | number // Can be string (ISO 8601) or number (seconds)
  viewCount: number
  channelId: string
  channelTitle: string
  url: string
}

export interface YouTubeChannel {
  id: string
  title: string
  description: string
  thumbnailUrl: string
  subscriberCount: number
  videoCount: number
  url: string
}

export interface SubtitleTrack {
  language: string
  languageCode: string
  isAutoGenerated: boolean
  url: string
}

export interface VideoSubtitles {
  videoId: string
  subtitles: string
  language: string
  isAutoGenerated: boolean
}

export interface ProcessingStatus {
  channelId: string
  channelName: string
  totalVideos: number
  processedVideos: number
  videosWithSubtitles: number
  currentVideo?: string
  status: 'idle' | 'fetching_videos' | 'processing_subtitles' | 'completed' | 'error'
  error?: string
  startTime: Date
  estimatedTimeRemaining?: number
}

export interface YouTubeError {
  message: string
  code: string
  details?: any
}
